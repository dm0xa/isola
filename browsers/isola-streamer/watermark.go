const (
	wmPixelScale = 2 // each font pixel is 2x2 surface pixels
	wmAlpha      = 0.35
	wmShadow     = 0.35 // darkening of the shadow outline beneath the glyphs
)

// stampWatermark draws watermarkText into dst (BGRA, stride bytes/row) at
// the bottom-right corner with a dark shadow behind it. No-op when the
// watermark is disabled or the text is empty.
func stampWatermark(dst []byte, stride, height uint32) {
	text := strings.TrimSpace(watermarkText)
	if text == "" || len(dst) == 0 || stride < 4 {
		return
	}

	text = strings.ToLower(text)
	charW := 5 * wmPixelScale
	charH := 7 * wmPixelScale
	spaceW := wmPixelScale
	marginX := uint32(16)
	marginY := uint32(12)

	totalW := 0
	for i := 0; i < len(text); i++ {
		if text[i] == ' ' {
			totalW += spaceW
		} else {
			totalW += charW + spaceW
		}
	}
	// Surface pixel width is stride/4 (BGRA).
	maxX := stride/4 - 1 - marginX
	startX := int(maxX) - totalW
	startY := int(height) - int(marginY) - charH
	if startX < int(marginX) || startY < 0 {
		return // surface too small for the mark — skip rather than corrupt
	}

	drawLine := func(startX, startY int) {
		x := startX
		for i := 0; i < len(text); i++ {
			ch := text[i]
			if ch == ' ' {
				x += spaceW
				continue
			}
			glyph, ok := font5x7[ch]
			if !ok {
				glyph = font5x7['?']
			}
			drawGlyph(dst, stride, height, glyph, x, startY)
			x += charW + spaceW
		}
	}

	if watermarkMode == "grid" {
		// Deterrent tiling: one stamp per quadrant (offset to keep the
		// bottom-right original in place), diagonal alternation.
		w := int(stride / 4)
		h := int(height)
		textW := totalW
		if textW <= 0 {
			return
		}
		cx := w / 2
		cy := h / 2
		if cx-textW-int(marginX) > 0 && cy-charH > int(marginY) {
			drawLine((cx-textW)/2, cy/2)
		}
		if cx-textW-int(marginX) > 0 {
			drawLine((cx-textW)/2, cy+cy/2-charH)
		}
		drawLine(startX, startY) // bottom-right always
		return
	}
	drawLine(startX, startY)
}

// drawGlyph blits one 5x7 glyph (scaled, shadowed) at surface pixel (ox, oy).
func drawGlyph(dst []byte, stride, height uint32, glyph [5]byte, ox, oy int) {
	for col := 0; col < 5; col++ {
		bits := glyph[col]
		for row := 0; row < 7; row++ {
			if bits&(1<<row) == 0 {
				continue
			}
			for dx := 0; dx < wmPixelScale; dx++ {
				for dy := 0; dy < wmPixelScale; dy++ {
					px := ox + col*wmPixelScale + dx
					py := oy + row*wmPixelScale + dy
					// Shadow first at (1,1) offset, then the lit pixel —
					// done by stamping both in one pass; where both hit,
					// the glyph wins.
					blendPixel(dst, stride, height, px+1, py+1, 0, 0, 0, wmShadow)
					blendPixel(dst, stride, height, px, py, 255, 255, 255, wmAlpha)
				}
			}
		}
	}
}

// blendPixel alpha-blends r,g,b over the BGRA pixel at (x,y).
func blendPixel(dst []byte, stride, height uint32, x, y int, r, g, b uint8, a float64) {
	if x < 0 || y < 0 || uint32(x) >= stride/4 || uint32(y) >= height {
		return
	}
	off := int(stride)*y + x*4
	dst[off+0] = uint8(float64(dst[off+0])*(1-a) + float64(b)*a)
	dst[off+1] = uint8(float64(dst[off+1])*(1-a) + float64(g)*a)
	dst[off+2] = uint8(float64(dst[off+2])*(1-a) + float64(r)*a)
	// Alpha channel (off+3) untouched.
}
