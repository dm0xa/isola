package main

// Frame-level session watermark: identity text alpha-blended into the raw
// BGRA surface before the encoder consumes it. Stamping at the Snapshot
// boundary means every frame fed to ffmpeg carries the mark regardless of
// damage-rect suppression — DOM overlays and client-side covers cannot strip
// it, because it is pixels by the time anything downstream looks at them.
//
// Enabled only when ISOLA_WATERMARK_TEXT is set (injected per container when
// the deployment enables watermarking); the default build never sets it, so
// the cost is one string compare per frame.

import (
	"os"
	"strings"
)

var watermarkText = os.Getenv("ISOLA_WATERMARK_TEXT")
var watermarkMode = os.Getenv("ISOLA_WATERMARK_MODE") // "" | "text" | "grid"

